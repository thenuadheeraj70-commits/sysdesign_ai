def startup_messages() -> list[tuple[str, str]]:
    """(level, text) pairs describing setup problems, logged once when the server starts."""
    messages: list[tuple[str, str]] = []
    anthropic_key = os.getenv("ANTHROPIC_API_KEY", "").strip()
    gemini_key = os.getenv("GEMINI_API_KEY", "").strip()
    has_key = any(k and not k.startswith("your-") for k in (anthropic_key, gemini_key))
    if DEMO_MODE:
        messages.append(
            ("warning", "DEMO_MODE is on: architectures and requirements are canned samples, not generated by AI.")
        )
    elif not has_key:
        messages.append(
            (
                "warning",
                "No AI key is set (GEMINI_API_KEY or ANTHROPIC_API_KEY, or it is still the placeholder), so "
                "generating an architecture will fail. Add your key to backend/.env, or set DEMO_MODE=true to "
                "try the app with sample data.",
            )
        )
    if SECRET_KEY_IS_EPHEMERAL:
        messages.append(
            (
                "warning",
                "Could not save a generated secret key, so logins reset on every restart. "
                "Set SECRET_KEY in backend/.env.",
            )
        )
    elif os.getenv("SECRET_KEY") and len(os.getenv("SECRET_KEY", "")) < 32:
        messages.append(("warning", "SECRET_KEY is shorter than 32 characters; use a long random value."))
    return messages
