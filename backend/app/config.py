# Signs login tokens. Set a long random value in production; if unset, a random one is
# generated per process (everyone is logged out on restart).
def _load_secret_key() -> tuple[str, bool]:
    """(key, is_ephemeral). Uses SECRET_KEY if set, else a key generated once and saved."""
    env = os.getenv("SECRET_KEY")
    if env:
        return env, False
    path = os.path.join(os.path.dirname(DB_PATH), ".secret_key")
    try:
        with open(path, encoding="utf-8") as f:
            saved = f.read().strip()
        if len(saved) >= 32:
            return saved, False
    except OSError:
        pass
    key = os.urandom(32).hex()
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(key)
        try:
            os.chmod(path, 0o600)
        except OSError:
            pass
        return key, False
    except OSError:
        return key, True  # could not save: logins reset on restart


SECRET_KEY, SECRET_KEY_IS_EPHEMERAL = _load_secret_key()
