"""Package generated infrastructure code into a ZIP file (in memory).

The ZIP contains:

    terraform/    the generated Terraform files
    kubernetes/   the generated Kubernetes YAML files
    README.md     what was generated, and how to inspect it

Nothing is written to disk, and nothing is run. Terraform and kubectl are never
executed and no cloud provider or cluster is contacted. The README only explains,
in text, how a person can inspect the files themselves.
"""

import io
import re
import zipfile

from app.schemas.models import ArchitectureResult
from app.services.code_generation import GenerateCodeResult, generate_code

DEFAULT_ARCHIVE_NAME = "sysdesign-ai"


# ---------- Text helpers (keep AI-written text from breaking the Markdown) ----------


def _one_line(text) -> str:
    return " ".join(str(text).split())


def _md(text) -> str:
    """One line of text with Markdown and HTML characters escaped."""
    return re.sub(r"([\\`*_\[\]<>|])", r"\\\1", _one_line(text))


def _code(text) -> str:
    """Inline code. Backticks inside are removed so they cannot end the span early."""
    return f"`{_one_line(text).replace('`', '')}`"


def archive_filename(project_name: str) -> str:
    """A safe download name such as 'demo-shop-infrastructure.zip' (letters, digits, '-')."""
    slug = re.sub(r"[^a-z0-9]+", "-", str(project_name).lower()).strip("-")[:50].strip("-")
    return f"{slug or DEFAULT_ARCHIVE_NAME}-infrastructure.zip"


# ---------- README ----------


def build_readme(architecture: ArchitectureResult, code: GenerateCodeResult) -> str:
    names = {c.id: c.name for c in architecture.components}
    tf_resources = {g["id"]: g["terraform_resources"] for g in code.terraform.generated_components}
    k8s_skipped = {s.id for s in code.kubernetes.skipped_components}
    k8s_has_workloads = not code.kubernetes.message.startswith("No application service")

    lines: list[str] = []
    add = lines.append

    add(f"# {_md(architecture.project_name)}")
    add("")
    add("Generated by SysDesign AI.")
    add("")
    add(
        "> **These files are a starting point.** They have not been applied, deployed or "
        "tested, and nothing was run to create them. Review everything before using it."
    )
    add("")

    # --- Architecture ---
    add("## Architecture")
    add("")
    add(_md(architecture.description) if architecture.description.strip() else "No description was provided.")
    add("")
    add(
        f"The design has {len(architecture.components)} component(s) and {len(architecture.connections)} connection(s)."
    )
    if architecture.connections:
        add("")
        add("Connections:")
        add("")
        for conn in architecture.connections:
            label = f" ({_md(conn.label)})" if conn.label.strip() else ""
            add(f"- {_md(names.get(conn.source, conn.source))} → {_md(names.get(conn.target, conn.target))}{label}")
    add("")

    # --- Components ---
    add("## Components")
    add("")
    if not architecture.components:
        add("This architecture has no components.")
        add("")
    for c in architecture.components:
        add(f"### {_md(c.name)}")
        add("")
        add(f"- ID: {_code(c.id)}")
        add(f"- Type: {_md(c.type)}")
        add(f"- Provider: {_md(c.provider)}")
        if c.id in tf_resources:
            add("- Terraform: " + ", ".join(_code(r) for r in tf_resources[c.id]))
        else:
            add("- Terraform: not generated")
        if k8s_has_workloads and c.id not in k8s_skipped:
            add("- Kubernetes: Deployment, Service, ConfigMap and HorizontalPodAutoscaler")
        else:
            add("- Kubernetes: not generated")
        add("")

    # --- Assumptions ---
    add("## Assumptions")
    add("")
    if architecture.assumptions:
        for a in architecture.assumptions:
            add(f"- {_md(a)}")
    else:
        add("No assumptions were recorded.")
    add("")

    # --- Contents ---
    add("## What is in this ZIP")
    add("")
    add("```text")
    add("terraform/     Terraform files (AWS)")
    for f in code.terraform.files:
        add(f"  {f.path.rsplit('/', 1)[-1]}")
    add("kubernetes/    Kubernetes YAML")
    for f in code.kubernetes.files:
        add(f"  {f.path.rsplit('/', 1)[-1]}")
    add("README.md      this file")
    add("```")
    add("")

    # --- How to inspect ---
    add("## How to inspect the generated files")
    add("")
    add("Nothing in this ZIP runs by itself. Start by reading the files:")
    add("")
    add(
        "1. Open `terraform/main.tf` to see the resources. `variables.tf` holds the "
        "settings you are most likely to change, `providers.tf` the provider setup, "
        "and `outputs.tf` the values shown after an apply."
    )
    add(
        "2. Open `kubernetes/deployment.yaml`, `service.yaml`, `configmap.yaml`, `hpa.yaml` and "
        "`ingress.yaml` to see the workloads and their resource limits, how they are exposed, "
        "their settings, and how they autoscale."
    )
    add("3. Read the notes below. They list what needs your attention.")
    add("")
    add("Optional checks that do not create anything (run them yourself, if you have the tools installed):")
    add("")
    add("```bash")
    add("# Terraform: format check and syntax/consistency check (no cloud account needed)")
    add("cd terraform")
    add("terraform fmt -check")
    add("terraform init -backend=false")
    add("terraform validate")
    add("")
    add("# Kubernetes: check the YAML without creating anything")
    add("# (kubectl may still need a configured cluster context)")
    add("cd ..")
    add("kubectl apply --dry-run=client -f kubernetes/")
    add("```")
    add("")
    add(
        "`terraform plan` shows what Terraform would create, and needs cloud credentials. "
        "It changes nothing, but read its output carefully. Do not run `terraform apply` "
        "or `kubectl apply` for real until you have reviewed the code and the plan."
    )
    add("")

    # --- Notes ---
    add("## Notes from the generators")
    add("")
    notes = [("Terraform", w) for w in code.terraform.warnings] + [("Kubernetes", w) for w in code.kubernetes.warnings]
    if notes:
        add("Things to check:")
        add("")
        for source, text in notes:
            add(f"- {source}: {_md(text)}")
        add("")

    skipped = [("Terraform", s) for s in code.terraform.skipped_components] + [
        ("Kubernetes", s) for s in code.kubernetes.skipped_components
    ]
    if skipped:
        add("Components that were not generated:")
        add("")
        for source, s in skipped:
            add(f"- {source}: {_md(s.name)}. {_md(s.reason)}")
        add("")

    add("General notes:")
    add("")
    add(f"- Terraform: {_md(code.terraform.notice)}")
    if code.kubernetes.notice:
        add(f"- Kubernetes: {_md(code.kubernetes.notice)}")
    add(f"- {_md(code.notice)}")
    add("")

    return "\n".join(lines)


# ---------- ZIP ----------


def _entry_name(folder: str, path: str) -> str:
    """Put every file directly inside its folder, whatever path the generator gave."""
    base = path.replace("\\", "/").rsplit("/", 1)[-1].strip()
    if not base or base in {".", ".."}:
        raise ValueError(f"Invalid generated file name: {path!r}")
    return f"{folder}/{base}"


def build_infrastructure_zip(architecture: ArchitectureResult | dict, region: str | None = None) -> tuple[bytes, str]:
    """Generate the code and package it. Returns (zip_bytes, download_filename)."""
    if not isinstance(architecture, ArchitectureResult):
        architecture = ArchitectureResult.model_validate(architecture)

    code = generate_code(architecture, region=region)

    entries: dict[str, str] = {}
    for f in code.terraform.files:
        entries[_entry_name("terraform", f.path)] = f.content
    for f in code.kubernetes.files:
        entries[_entry_name("kubernetes", f.path)] = f.content
    entries["README.md"] = build_readme(architecture, code)

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in entries.items():
            archive.writestr(name, content.encode("utf-8"))

    return buffer.getvalue(), archive_filename(architecture.project_name)
