def terms_in(text: str) -> list[str]:
    """Glossary terms that appear in the text (case-insensitive), longest first so 'Read replica' wins over 'Replica'."""
    lowered = text.lower()
    return [t for t in sorted(GLOSSARY, key=len, reverse=True) if t.lower() in lowered]
